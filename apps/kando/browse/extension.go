//go:generate go run ./extgen

// The browser extension (resources/browser-extension, browserext): the same buttons as the built-in browser's pages in the pages of the sites the buttons know, in the user's own browser, which speak to Kando through the extension's background and Kando's native messaging host. The files that come from the buttons' code and data are written here (ExtensionFiles) and committed, as the browsers load the folder as it is; go generate in this folder writes them again (extgen), and TestExtensionFilesAreCurrent fails while they are not.

// ExtensionScript is the extension's content script: the page's buttons (buttonsScript), speaking to the extension's background (extensionBridge).
func ExtensionScript() string {
	return "// Kando's buttons in the pages of video sites. Generated by apps/kando/browse (go generate); do not edit.\n" + buttonsScript(extensionBridge) + "\n"
}

// extensionSitesScript is the extension's sites.js, which its background and popup read: KANDO, with the host's name, the messages of the page's buttons, videoOf as the buttons read a link (sitesScript), title as they name a video by its page's title, and the patterns of the links its menu item shows on (menuPatterns).
func extensionSitesScript() string {
	menu, err := json.Marshal(menuPatterns())
	if err != nil {
		panic("browse: menu patterns: " + err.Error())
	}
	return `// The sites Kando's buttons know, for the extension's background and popup. Generated by apps/kando/browse (go generate); do not edit.
var KANDO = (() => {
  const MAX_URL = ` + strconv.Itoa(MaxVideoURL) + `;
` + sitesScript("undefined") + `  return {
    host: "` + browserext.HostName + `",
    ask: "` + AskMessage + `", add: "` + AddMessage + `", state: "` + StateMessage + `",
    maxAsk: ` + strconv.Itoa(MaxAsk) + `,
    notRunning: "` + browserext.CodeNotRunning + `",
    videoOf,
    // title is the name of the video at url by its page's title, without a leading count and the site's name after it, as the page's 下载视频 names it without a heading.
    title: (url, raw) => {
      let t = String(raw || "").replace(/\s+/g, " ").trim().replace(/^\(\d+\+?\) /, "");
      const s = siteOf(new URL(url).hostname);
      for (const cut of s ? s.cut : []) if (t.endsWith(cut)) t = t.slice(0, -cut.length).trim();
      return t;
    },
    menu: ` + string(menu) + `,
  };
})();
`
}

// contentMatches are the pages the content script runs in: those of every site the buttons know, its subdomains included (https://developer.chrome.com/docs/extensions/develop/concepts/match-patterns).
func contentMatches() []string {
	out := make([]string, len(videoSites))
	for i, s := range videoSites {
		out[i] = "*://*." + s.Domain + "/*"
	}
	return out
}

// menuPatterns are the links the extension's menu item shows on: those of each shape's Menu, on the site and its subdomains.
func menuPatterns() []string {
	var out []string
	for _, s := range videoSites {
		for _, v := range s.Videos {
			for _, path := range v.Menu {
				out = append(out, "*://*."+s.Domain+path)
			}
		}
	}
	return out
}

// extensionIcons are the extension's icons by their size, as its manifest names them.
var extensionIcons = map[string]string{"16": "icons/16.png", "32": "icons/32.png", "48": "icons/48.png", "128": "icons/128.png"}

// extensionManifest is the extension's manifest.json, one Manifest V3 file both browser families load: Chrome and the browsers built on Chromium start background.js as a service worker and ignore background.scripts, and Firefox, which has no service workers, starts the scripts as an event page and ignores service_worker (https://developer.mozilla.org/en-US/docs/Mozilla/Add-ons/WebExtensions/manifest.json/background#browser_support). Its version is the app's, from nsgo.yaml.
func extensionManifest(version string) []byte {
	type script struct {
		Matches []string `json:"matches"`
		JS      []string `json:"js"`
		RunAt   string   `json:"run_at"`
	}
	type background struct {
		ServiceWorker string   `json:"service_worker"`
		Scripts       []string `json:"scripts"`
	}
	type action struct {
		DefaultTitle string            `json:"default_title"`
		DefaultPopup string            `json:"default_popup"`
		DefaultIcon  map[string]string `json:"default_icon"`
	}
	type collection struct {
		Required []string `json:"required"`
	}
	type gecko struct {
		ID               string     `json:"id"`
		StrictMinVersion string     `json:"strict_min_version"`
		DataCollection   collection `json:"data_collection_permissions"`
	}
	type specific struct {
		Gecko gecko `json:"gecko"`
	}
	manifest := struct {
		ManifestVersion int               `json:"manifest_version"`
		Name            string            `json:"name"`
		Description     string            `json:"description"`
		Version         string            `json:"version"`
		DefaultLocale   string            `json:"default_locale"`
		Key             string            `json:"key"`
		Icons           map[string]string `json:"icons"`
		Permissions     []string          `json:"permissions"`
		Background      background        `json:"background"`
		Action          action            `json:"action"`
		ContentScripts  []script          `json:"content_scripts"`
		Specific        specific          `json:"browser_specific_settings"`
	}{
		ManifestVersion: 3,
		Name:            "__MSG_name__",
		Description:     "__MSG_description__",
		Version:         version,
		DefaultLocale:   "en",
		Key:             browserext.PublicKey,
		Icons:           extensionIcons,
		Permissions:     []string{"nativeMessaging", "contextMenus", "activeTab"},
		Background:      background{ServiceWorker: "background.js", Scripts: []string{"sites.js", "background.js"}},
		Action:          action{DefaultTitle: "__MSG_name__", DefaultPopup: "popup.html", DefaultIcon: extensionIcons},
		ContentScripts:  []script{{Matches: contentMatches(), JS: []string{"content.js"}, RunAt: "document_idle"}},
		// Firefox signs a Manifest V3 extension only with an ID of its own, and asks a new one what it collects: nothing leaves the computer, as the extension speaks only to Kando on it.
		Specific: specific{Gecko: gecko{ID: browserext.GeckoID, StrictMinVersion: "128.0", DataCollection: collection{Required: []string{"none"}}}},
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		panic("browse: extension manifest: " + err.Error())
	}
	return append(data, '\n')
}

// ExtensionFiles are the extension's files that come from the buttons' code and data, by their paths in its folder, for the app's version.
func ExtensionFiles(version string) map[string][]byte {
	return map[string][]byte{
		"manifest.json": extensionManifest(version),
		"content.js":    []byte(ExtensionScript()),
		"sites.js":      []byte(extensionSitesScript()),
	}
}

// AppVersion is the version nsgo.yaml, whose contents are data, gives the app, which the extension takes as its own.
func AppVersion(data []byte) (string, error) {
	for _, line := range strings.Split(string(data), "\n") {
		if v, ok := strings.CutPrefix(strings.TrimSpace(line), "version: "); ok && !strings.HasPrefix(line, " ") {
			return strings.TrimSpace(v), nil
		}
	}
	return "", errors.New("nsgo.yaml names no version")
}
